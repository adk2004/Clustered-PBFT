def generate_complexity_chart():
    """Bar chart showing message count: Our O(n^1.5) vs PBFT O(n^2)."""
    ps = np.array([8, 12, 16, 20, 32, 64, 100])
    our  = np.power(ps, 1.5)
    pbft = ps ** 2

    fig, ax = plt.subplots(figsize=(6, 3.6))
    x = np.arange(len(ps))
    ax.bar(x - BAR_WIDTH/2, pbft, BAR_WIDTH,
           color=PBFT_BAR_COLOR, label="PBFT O(n2)", edgecolor="white")
    ax.bar(x + BAR_WIDTH/2, our,  BAR_WIDTH,
           color=OUR_BAR_COLOR,  label="Our Protocol O(n^1.5)", edgecolor="white")
    ax.set_xticks(x)
    ax.set_xticklabels([str(p) for p in ps])
    ax.set_xlabel("Total Nodes (p)", fontsize=AXIS_SIZE)
    ax.set_ylabel("Message Count", fontsize=AXIS_SIZE)
    ax.set_title("Message Complexity: Our Protocol vs Classic PBFT\n"
                 "(Table II/III -- Paper Section XIII)",
                 fontsize=TITLE_SIZE, pad=6)
    ax.legend(fontsize=LEGEND_SIZE, framealpha=0.9)
    ax.yaxis.set_major_formatter(mtick.FuncFormatter(
        lambda x, _: f"{int(x):,}"))

    # Add speedup labels on top
    for i, (o, p_) in enumerate(zip(our, pbft)):
        ax.text(x[i], p_ + p_*0.03, f"{p_/o:.1f}x",
                ha="center", va="bottom", fontsize=7, color=PBFT_BAR_COLOR,
                fontweight="bold")

    fig.tight_layout()
    fig.savefig("fig_complexity.png")
    plt.close(fig)
    print("  OK  Saved fig_complexity.png")


# ---------------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------------

def main():
    ap = argparse.ArgumentParser(description="Plot paper figures from simulation CSVs")
    ap.add_argument("--static",  default="results_static.csv",
                    help="Static testbed CSV (default: results_static.csv)")
    ap.add_argument("--dynamic", default="results_dynamic.csv",
                    help="Dynamic testbed CSV (default: results_dynamic.csv)")
    args = ap.parse_args()

    set_paper_style()

    print("\n=== Vehicular BFT -- Figure Generator ==============================")

    # -- Load static data -------------------------------------------------------
    if not os.path.exists(args.static):
        print(f"  ERROR: {args.static} not found.")
        print("  Run:  go run main.go -paper-eval  (to generate CSV first)")
        sys.exit(1)

    df_static = pd.read_csv(args.static)
    required_static = {"nodes","rps","our_throughput","our_latency_ms",
                       "pbft_throughput","pbft_latency_ms"}
    if not required_static.issubset(df_static.columns):
        print(f"  ERROR: {args.static} missing columns: "
              f"{required_static - set(df_static.columns)}")
        sys.exit(1)
    print(f"\n  Loaded {args.static}: {len(df_static)} rows, "
          f"nodes={sorted(df_static['nodes'].unique())}, "
          f"rps={sorted(df_static['rps'].unique())}")

    # -- Load dynamic data -------------------------------------------------------
    df_dynamic = None
    if os.path.exists(args.dynamic):
        df_dynamic = pd.read_csv(args.dynamic)
        print(f"  Loaded {args.dynamic}: {len(df_dynamic)} rows, "
              f"tick_rates={sorted(df_dynamic['tick_rate_s'].unique())}")
    else:
        print(f"  WARNING: {args.dynamic} not found -- skipping Fig 8")

    print()

    # -- Generate figures -------------------------------------------------------
    generate_static_figures(df_static)

    if df_dynamic is not None:
        generate_dynamic_figure(df_dynamic)

    generate_complexity_chart()

    print("\n=== Summary of generated files =====================================")
    expected = ["fig4_8nodes.png","fig5_12nodes.png","fig6_16nodes.png",
                "fig7_20nodes.png","fig8_dynamic.png","fig_complexity.png",
                "all_figures.png"]
    for f in expected:
        status = "OK" if os.path.exists(f) else "MISSING"
        print(f"  {status}  {f}")

    print("\n  To regenerate with fresh simulation data:")
    print("    go run main.go -paper-eval")
    print("  To plot from existing CSVs only:")
    print("    python plot.py")
    print()


if __name__ == "__main__":
    main()